'use strict';
const assert=require('assert'),path=require('path');
const {game}=require(path.resolve(__dirname,'../../../kit/scripts/port_check.js'));
const {CPU}=require(path.resolve(__dirname,'../../../kit/cpu/cpu6502.js'));
const g=require('./layered.js')(game(__dirname)),{ram}=require('./opening_image.js')(g);
let seeds=0;
for(let seed=0;seed<65536;seed++){
 const c=new CPU(Uint8Array.from(ram));c.m[0x502]=seed&255;c.m[0x503]=seed>>8;c.call(0x4210,{d:0});
 assert.equal(c.m[0x502]+256*c.m[0x503],(37*seed+17)&65535);seeds++;
}
for(const [entry,dx,dy] of [[0x4a19,1,0],[0x4aa0,-1,0],[0x4b39,0,1],[0x4b9d,0,-1]]){
 const c=new CPU(Uint8Array.from(ram)),before=new Uint8Array(640);
 for(let i=0;i<640;i++)before[i]=c.m[0xcca0+i]=(i*37+(i>>5)*13)&255;
 c.call(entry,{d:0},{hooks:{0x4c7a:c=>c.rts(),0x4c01:c=>c.rts()}});
 for(let y=0;y<16;y++)for(let x=0;x<40;x++){
  const sx=x+dx,sy=y+dy;if(sx<0||sx>=40||sy<0||sy>=16)continue;
  assert.equal(c.m[0xcca0+y*40+x],before[sy*40+sx],`scroll $${entry.toString(16)}, ${x}/${y}`);
 }
}
// The initializer must prove both its generated bytes and the untouched boundaries.
{
 const c=new CPU(Uint8Array.from(ram));c.m.fill(0xa5,0xe000,0xea00);c.call(0x101a,{d:0});
 assert(c.m.slice(0xe000,0xe800).every(b=>b===0));assert.equal(c.m[0xe800],0xa5);
 c.m.fill(0xa5,0xea00,0xffc0);c.call(0x1096,{d:0});
 assert(c.m.slice(0xe801,0xe900).every(b=>b===0));assert(c.m.slice(0xe901,0xea00).every(b=>b===0));
 assert.equal(c.m[0xe800],0);assert.equal(c.m[0xe900],0);
 for(let page=0xea;page<=0xfe;page++){assert(c.m.slice(page*256,page*256+0xc0).every(b=>b===0));assert.equal(c.m[page*256+0xc0],0xa5);}
 assert(c.m.slice(0xff00,0xff80).every(b=>b===0));
 for(let a=0xff80;a<0xffc0;a++)assert.equal(c.m[a],[0xff8a,0xff8d].includes(a)?0x28:0);
}
for(let low=0;low<256;low++)for(const active of [0,255]){
 const c=new CPU(Uint8Array.from(ram));c.m[0x99]=low;c.m[0x9a]=0xcd;c.m[0x6995]=active;c.m[0x6996]=7;
 c.call(0x687d,{d:0});assert.equal(c.m[0x99],(low-40)&255);assert.equal(c.m[0x9a],0xcd);assert.equal(c.m[0x6996],active===255?7:6);
}
for(let slot=0;slot<7;slot++){
 const writes=[];const c=new CPU(Uint8Array.from(ram),{port:{dir:0x2f,data:0x25},io:{write(a,v){writes.push([a,v]);}}});c.m[0x1bdb+slot]=0x34;c.m[0x1bd4+slot]=0x12;c.m[0x1ba5+slot]=0x56;c.m[0x1ba8+slot]=0x78;
 c.call(0x1ef2,{x:slot,d:0});
 const o=ram[0x1f22+slot];assert(writes.some(([a,v])=>a===0xd400+o&&v===0x34));assert(writes.some(([a,v])=>a===0xd401+o&&v===0x12));
 if(slot<3){assert(writes.some(([a,v])=>a===0xd405+o&&v===0x56));assert(writes.some(([a,v])=>a===0xd406+o&&v===0x78));}
}
for(let h=0;h<256;h++){
 const v=255-h,c=new CPU(Uint8Array.from(ram));c.m[0x12]=255;c.m[0x13]=h;c.m[0x14]=v;c.m[0x2afb]=h^255;c.m[0x2afc]=v^255;
 c.call(0x2afd,{x:0,d:0});
 for(let k=0;k<64;k++){assert.equal(c.m[0xcb00+k]+256*c.m[0xcb40+k],(k+1)*(h+1));assert.equal(c.m[0xcb80+k]+256*c.m[0xcbc0+k],(k+1)*(v+1));}
}
console.log(`OK - ${seeds} random seeds, four screen shifts, initializer boundaries, 512 rewind states and seven sound-slot writes match`);
